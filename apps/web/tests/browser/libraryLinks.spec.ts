import { createServer, type Server } from 'node:http'
import { readFileSync } from 'node:fs'

let site: Server
let siteUrl: string
test.beforeAll(async () => {
  site = createServer((_, res) => {
    res.setHeader('Content-Type', 'text/html; charset=utf-8')
    res.end('<html><body><h1>Resultados del concurso</h1></body></html>')
  })
  await new Promise<void>(resolve => site.listen(0, 'localhost', resolve))
  const address = site.address()
  if (!address || typeof address === 'string') throw new Error('Test site did not start.')
  siteUrl = `http://localhost:${address.port}/results`
})
test.afterAll(async () => { await new Promise<void>((resolve, reject) => site.close(error => error ? reject(error) : resolve())) })

