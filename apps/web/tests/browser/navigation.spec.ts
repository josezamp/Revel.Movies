import { test, expect } from './adminFixture'

test('event and section survive reload, shared links and browser history', async ({ page, request }) => {
  const first = await (await request.post('/api/events', { data: { name: 'Fiesta de bienvenida' } })).json()
  const second = await (await request.post('/api/events', { data: { name: 'Evento siguiente' } })).json()
  await page.goto('/admin')
  await page.getByLabel('Evento activo').selectOption(first.id)
  await page.getByRole('button', { name: 'Contenido', exact: true }).click()
  await page.reload()
  await expect(page.getByLabel('Evento activo')).toHaveValue(first.id)
  await expect(page.getByRole('button', { name: 'Contenido', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('button', { name: 'Configuración', exact: true }).click()
  await page.getByLabel('Evento activo').selectOption(second.id)
  await page.goBack()
  await expect(page.getByLabel('Evento activo')).toHaveValue(first.id)
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Contenido', exact: true })).toHaveAttribute('aria-current', 'page')
  const sharedLink = page.url()
  await page.goto('/')
  await page.goto(sharedLink)
  await expect(page.getByLabel('Evento activo')).toHaveValue(first.id)
  await expect(page.getByRole('heading', { name: first.name, exact: true })).toBeVisible()
})

test('an unavailable event link never silently selects a different event', async ({ page, request }) => {
  const existing = await (await request.post('/api/events', { data: { name: 'Evento disponible' } })).json()
  await page.goto('/admin?event=00000000-0000-0000-0000-000000000000&section=scenes')
  await expect(page.getByRole('alert').filter({ hasText: 'Este evento no está disponible' })).toBeVisible()
  await expect(page.getByLabel('Evento activo')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Crear escena', exact: true })).toHaveCount(0)
  await page.getByLabel('Evento activo').selectOption(existing.id)
  await expect(page.getByRole('heading', { name: existing.name, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Crear escena', exact: true })).toBeEnabled()
})

