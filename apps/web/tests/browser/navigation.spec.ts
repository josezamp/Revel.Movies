test('creating an event selects it immediately and keeps that selection after reload', async ({ page }) => {
  await page.goto('/admin')
  await page.getByRole('button', { name: 'Nuevo evento', exact: true }).click()
  await page.getByLabel('Nombre del evento').fill('Revel · Noche de disfraces')
  await page.getByRole('button', { name: 'Crear evento', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const selected = await page.getByLabel('Evento activo').inputValue()
  expect(selected).not.toBe('')
  await page.reload()
  await expect(page.getByLabel('Evento activo')).toHaveValue(selected)
  await expect(page.getByRole('heading', { name: 'Revel · Noche de disfraces', exact: true })).toBeVisible()
})
