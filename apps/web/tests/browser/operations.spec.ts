import { test, expect, type Page, type APIRequestContext } from './adminFixture'

async function setup(page: Page, request: APIRequestContext) {
  const event = await (await request.post('/api/events', { data: { name: `Operación ${Date.now()}`, timeZone: 'UTC' } })).json()
  await page.goto('/player')
  await expect(page.locator('.pairing-code')).toHaveText(/\d{3} \d{3}/)
  const code = (await page.locator('.pairing-code').innerText()).replace(/\s/g, '')
  const display = await (await request.post('/api/displays/pair', { data: { code, name: 'TV Patio', eventId: event.id } })).json()
  await expect(page.locator('.pairing-screen')).toHaveCount(0)
  return { event, display }
}

test('offline rename persists identity; mobile retains data through server errors and exposes usable controls', async ({ page, context, request }, testInfo) => {
  const { event, display } = await setup(page, request)
  const admin = await context.newPage()
  await admin.setViewportSize({ width: 360, height: 800 })
  await page.goto('about:blank')
  await admin.goto('/admin')
  await admin.locator('header select').selectOption(event.id)
  await admin.getByRole('button', { name: 'Renombrar', exact: true }).click()
  await admin.getByRole('textbox', { name: 'Nombre', exact: true }).fill('TV Patio Norte')
  await admin.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(admin.getByRole('heading', { name: 'TV Patio Norte', exact: true })).toBeVisible()
  const current = (await (await request.get(`/api/displays?eventId=${event.id}`)).json())[0]
  expect(current.id).toBe(display.id)
  expect(current.eventId).toBe(event.id)
  expect(current.name).toBe('TV Patio Norte')
  await expect(admin.getByRole('button', { name: 'Renombrar', exact: true })).toBeFocused()
  for (const label of ['Escenas', 'Contenido', 'Configuración', 'En vivo']) {
    await admin.getByRole('button', { name: label, exact: true }).click()
    expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  await admin.screenshot({ path: testInfo.outputPath('mobile-live.png'), fullPage: true, animations: 'disabled' })
  await admin.route('**/api/displays', route => route.abort())
  await expect(admin.getByRole('alert').filter({ hasText: 'Sin actualización del servidor' })).toBeVisible({ timeout: 12000 })
  await expect(admin.getByRole('heading', { name: 'TV Patio Norte', exact: true })).toBeVisible()
  await admin.unroute('**/api/displays')
  await expect(admin.getByRole('alert').filter({ hasText: 'Sin actualización del servidor' })).toHaveCount(0, { timeout: 12000 })
  await admin.close()
})

test('scene editor saves a draft, prepares without activating, then displays confirmed activation and return', async ({ page, context, request }, testInfo) => {
  const { event } = await setup(page, request)
  const admin = await context.newPage()
  await admin.goto('/admin')
  await admin.locator('header select').selectOption(event.id)
  await admin.getByRole('button', { name: 'Escenas', exact: true }).click()
  await admin.getByRole('button', { name: 'Crear escena', exact: true }).click()
  await admin.getByRole('textbox', { name: 'Nombre de la escena' }).fill('Sorteo')
  await admin.getByRole('button', { name: '+ Agregar asignación' }).click()
  await admin.getByRole('checkbox', { name: 'TV Patio', exact: true }).check()
  await admin.getByRole('combobox', { name: 'Anuncio o cuenta regresiva', exact: true }).selectOption('replace')
  await admin.getByRole('combobox', { name: 'Tipo de anuncio', exact: true }).selectOption('countdown')
  await admin.getByRole('combobox', { name: 'Inicio de la cuenta', exact: true }).selectOption('fixed')
  await admin.getByRole('combobox', { name: 'Inicio de la cuenta', exact: true }).selectOption('duration')
  await admin.getByLabel('Texto del anuncio', { exact: true }).fill('El sorteo comienza pronto')
  await admin.setViewportSize({ width: 360, height: 800 })
  expect(await admin.locator('dialog').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy()
  await admin.screenshot({ path: testInfo.outputPath('mobile-scene-editor.png'), fullPage: true, animations: 'disabled' })
  await admin.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(admin.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('El sorteo comienza pronto', { exact: true })).toHaveCount(0)
  const card = admin.locator('.scene-card').filter({ has: admin.getByRole('heading', { name: 'Sorteo', exact: true }) })
  await card.getByRole('button', { name: 'Preparar recursos' }).click()
  await expect(card.getByText('1 de 1 lista en caché')).toBeVisible({ timeout: 15000 })
  await expect(page.getByText('El sorteo comienza pronto', { exact: true })).toHaveCount(0)
  await card.getByRole('button', { name: 'Activar Sorteo en 1 pantalla', exact: true }).click()
  await expect(page.getByText('El sorteo comienza pronto', { exact: true })).toBeVisible({ timeout: 15000 })
  await expect(card.getByLabel('Resultados de activación').getByText('Aplicada', { exact: true })).toBeVisible({ timeout: 15000 })
  await card.getByRole('button', { name: 'Volver a la configuración anterior' }).click()
  await expect(page.getByText('El sorteo comienza pronto', { exact: true })).toHaveCount(0)
  await admin.setViewportSize({ width: 1440, height: 1000 })
  await admin.evaluate(() => window.scrollTo(0, 0))
  await admin.screenshot({ path: testInfo.outputPath('desktop-scenes.png'), fullPage: true, animations: 'disabled' })
  await admin.close()
})

test('live cards follow the actual playlist item and preserve its sent item count after an edit', async ({ page, context, request }, testInfo) => {
  const { event, display } = await setup(page, request)
  const pixel = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a5S8AAAAASUVORK5CYII=', 'base64')
  const assets = []
  for (const name of ['Bienvenida.png', 'Fiesta.png']) {
    const uploaded = await request.post(`/api/events/${event.id}/media`, { multipart: { file: { name, mimeType: 'image/png', buffer: pixel } } })
    expect(uploaded.ok()).toBeTruthy()
    assets.push(await uploaded.json())
  }
  const playlist = await (await request.post(`/api/events/${event.id}/playlists`, { data: { name: 'Ambientación', isLoop: true, items: assets.map(asset => ({ mediaAssetId: asset.id, durationSeconds: 4 })) } })).json()
  const response = await request.post(`/api/playlists/${playlist.id}/play`, { data: { targetType: 'display', targetId: display.id } })
  expect(response.ok()).toBeTruthy()
  const admin = await context.newPage()
  await admin.goto('/admin')
  await admin.getByRole('combobox', { name: 'Evento activo' }).selectOption(event.id)
  const content = admin.locator('.display-card .live-content')
  await expect(content.getByText('Bienvenida', { exact: true })).toBeVisible({ timeout: 12000 })
  await expect(content.getByText('Fiesta', { exact: true })).toBeVisible({ timeout: 12000 })
  expect((await request.put(`/api/playlists/${playlist.id}/items`, { data: { items: [{ mediaAssetId: assets[0].id, durationSeconds: 4 }] } })).ok()).toBeTruthy()
  await admin.getByRole('button', { name: 'Contenido', exact: true }).click()
  await admin.getByRole('button', { name: 'En vivo', exact: true }).click()
  await expect(content.getByText(/Ambientación.*de 2.*versión anterior al aire/)).toBeVisible({ timeout: 12000 })
  const announcement = await request.post(`/api/displays/${display.id}/commands`, { data: { type: 'announcement.show', payload: { kind: 'message', text: 'Acercate al salón', layout: 'banner', theme: 'dark' } } })
  expect(announcement.ok()).toBeTruthy()
  await expect(content.getByText('Acercate al salón', { exact: true })).toBeVisible({ timeout: 12000 })
  await expect(content.getByText(/^De fondo:/)).toBeVisible()
  await admin.setViewportSize({ width: 1440, height: 1000 })
  await admin.screenshot({ path: testInfo.outputPath('desktop-live.png'), fullPage: true })
  await admin.close()
})
