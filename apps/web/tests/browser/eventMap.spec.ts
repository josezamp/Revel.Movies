test('touch dragging moves an element and cancellation restores its position', async ({ browser, context, request }) => {
  const event = await createEvent(request)
  const touchContext = await browser.newContext({ storageState: await context.storageState(), hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 } })
  const page = await touchContext.newPage()
  await openMap(page, event.id)
  await page.getByRole('button', { name: 'Editar croquis', exact: true }).tap()
  await page.getByRole('button', { name: 'Sector', exact: true }).tap()
  const node = page.getByRole('button', { name: 'Sector: Sector', exact: true })
  await node.scrollIntoViewIfNeeded()
  const rect = (await node.boundingBox())!
  const client = await touchContext.newCDPSession(page)
  const start = { x: rect.x + 30, y: rect.y + 30 }
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x + 40, y: start.y + 30 }] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.getByLabel('Posición X')).toHaveValue('200')
  await expect(page.getByLabel('Posición Y')).toHaveValue('180')
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: start.x + 40, y: start.y + 30 }] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x + 60, y: start.y + 50 }] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await expect(page.getByLabel('Posición X')).toHaveValue('200')
  await expect(page.getByLabel('Posición Y')).toHaveValue('180')
  await touchContext.close()
})
