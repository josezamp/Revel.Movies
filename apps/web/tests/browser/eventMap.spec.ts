test('failed saves keep the draft; a stale editor cannot overwrite another operator', async ({ page, request }) => {
  const event = await createEvent(request)
  const other = await createEvent(request)
  await openMap(page, event.id)
  await page.getByRole('button', { name: 'Editar croquis', exact: true }).click()
  await page.getByRole('button', { name: 'Sector', exact: true }).click()
  await page.getByLabel('Etiqueta', { exact: true }).fill('Mi borrador')
  await page.route(`**/api/events/${event.id}/map`, route => route.request().method() === 'PUT' ? route.abort() : route.continue())
  await page.getByRole('button', { name: 'Guardar croquis', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByText('Cambios sin guardar', { exact: true })).toBeVisible()
  await page.getByLabel('Evento activo').selectOption(other.id)
  await expect(page.locator('.map-node')).toHaveCount(0)
  await page.getByLabel('Evento activo').selectOption(event.id)
  await expect(page.getByRole('button', { name: 'Sector: Mi borrador', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Editar croquis', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.unroute(`**/api/events/${event.id}/map`)
  await page.route(`**/api/events/${event.id}/map`, route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 409, json: { error: 'Hay una limpieza de archivos en curso. Reintentá al finalizar.' } }) : route.continue())
  await page.getByRole('button', { name: 'Guardar croquis', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('limpieza de archivos')
  await expect(page.getByRole('button', { name: 'Guardar croquis', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Cargar versión guardada', exact: true })).toHaveCount(0)
  await page.unroute(`**/api/events/${event.id}/map`)
  const remote = { id: '145fe34a-162e-44e4-b466-334780923c12', kind: 'label', x: 100, y: 300, width: 240, height: 50, label: 'Guardado por otro operador', color: 'blue', displayId: null }
  expect((await request.put(`/api/events/${event.id}/map`, { data: { version: 0, nodes: [remote] } })).ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Guardar croquis', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cargar versión guardada', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sector: Mi borrador', exact: true })).toBeVisible()
  expect((await (await request.get(`/api/events/${event.id}/map`)).json()).nodes).toEqual([remote])
  await page.getByRole('button', { name: 'Cargar versión guardada', exact: true }).click()
  await page.getByRole('button', { name: 'Descartar y cargar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.map-node')).toHaveText('Guardado por otro operador')
  await expect(page.getByRole('button', { name: 'Operar', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

