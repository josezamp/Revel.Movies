test('resize cancellation restores all four coordinates and minimum size stays usable at the canvas edge', async ({ page, request }) => {
  const event = await createEvent(request)
  await openMap(page, event.id)
  await page.getByRole('button', { name: 'Editar croquis', exact: true }).click()
  await page.getByRole('button', { name: 'Sector', exact: true }).click()
  const handle = page.getByRole('button', { name: 'Cambiar tamaño desde esquina superior izquierda', exact: true })
  await handle.scrollIntoViewIfNeeded()
  const rect = (await handle.boundingBox())!
  await page.mouse.move(rect.x + 12, rect.y + 12)
  await page.mouse.down()
  await page.mouse.move(rect.x + 42, rect.y + 37, { steps: 6 })
  await expect(page.getByLabel('Posición X')).not.toHaveValue('120')
  await expect(page.getByLabel('Ancho', { exact: true })).not.toHaveValue('240')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(page.getByLabel('Posición X')).toHaveValue('120')
  await expect(page.getByLabel('Posición Y')).toHaveValue('120')
  await expect(page.getByLabel('Ancho', { exact: true })).toHaveValue('240')
  await expect(page.getByLabel('Alto', { exact: true })).toHaveValue('140')

  await page.getByLabel('Posición X').fill('0')
  await page.getByLabel('Posición Y').fill('0')
  const corner = page.getByRole('button', { name: 'Cambiar tamaño desde esquina inferior derecha', exact: true })
  await corner.scrollIntoViewIfNeeded()
  const start = (await corner.boundingBox())!
  const canvasRect = (await page.locator('.map-canvas').boundingBox())!
  await page.mouse.move(start.x + 12, start.y + 12)
  await page.mouse.down()
  await page.mouse.move(canvasRect.x, canvasRect.y, { steps: 8 })
  await page.mouse.up()
  await expect(page.getByLabel('Ancho', { exact: true })).toHaveValue('8')
  await expect(page.getByLabel('Alto', { exact: true })).toHaveValue('8')
  const small = (await corner.boundingBox())!
  await page.mouse.move(small.x + 12, small.y + 12)
  await page.mouse.down()
  await page.mouse.move(small.x + 70, small.y + 70, { steps: 8 })
  await page.mouse.up()
  expect(Number(await page.getByLabel('Ancho', { exact: true }).inputValue())).toBeGreaterThan(8)
  expect(Number(await page.getByLabel('Alto', { exact: true }).inputValue())).toBeGreaterThan(8)
})
