import { test, expect, type Page, type APIRequestContext } from './adminFixture'

async function createEvent(request: APIRequestContext, name = 'Mapa del evento') {
  const response = await request.post('/api/events', { data: { name: `${name} ${Date.now()}` } })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

async function openMap(page: Page, eventId: string) {
  await page.goto(`/admin?event=${eventId}&section=live&view=map`)
  await expect(page.getByRole('button', { name: 'Editar croquis', exact: true })).toBeVisible()
}

async function dragNode(page: Page, label: string, dx: number, dy: number) {
  const node = page.getByRole('button', { name: label, exact: true })
  await node.scrollIntoViewIfNeeded()
  const rect = (await node.boundingBox())!
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width / 2 + dx, rect.y + rect.height / 2 + dy, { steps: 8 })
  await page.mouse.up()
}

