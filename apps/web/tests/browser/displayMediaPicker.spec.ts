import { test, expect, type APIRequestContext, type Page } from './adminFixture'
import { readFileSync } from 'node:fs'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a5S8AAAAASUVORK5CYII=', 'base64')

async function setup(player: Page, request: APIRequestContext) {
  const event = await (await request.post('/api/events', { data: { name: `Selector ${Date.now()}`, timeZone: 'UTC' } })).json()
  await player.goto('/player')
  await expect(player.locator('.pairing-code')).toHaveText(/\d{3} \d{3}/)
  const code = (await player.locator('.pairing-code').innerText()).replace(/\s/g, '')
  const display = await (await request.post('/api/displays/pair', { data: { code, name: 'TV Patio', eventId: event.id } })).json()
  await expect(player.locator('.pairing-screen')).toHaveCount(0)
  const uploaded = await request.post(`/api/events/${event.id}/media`, { multipart: { file: { name: 'Recepción.png', mimeType: 'image/png', buffer: png } } })
  expect(uploaded.ok()).toBeTruthy()
  const image = await uploaded.json()
  const playlist = await (await request.post(`/api/events/${event.id}/playlists`, { data: {
    name: 'Ambientación', isLoop: true, items: [{ mediaAssetId: image.id, durationSeconds: 60 }],
  } })).json()
  return { event, display, image, playlist }
}

test('visual picker separates content, searches without accents, restores focus and fits mobile', async ({ page: player, context, request }, testInfo) => {
  const { event } = await setup(player, request)
  const preview = readFileSync(new URL('../fixtures/picker-preview.mp4', import.meta.url))
  expect((await request.post(`/api/events/${event.id}/media`, { multipart: { file: { name: 'Apertura.mp4', mimeType: 'video/mp4', buffer: preview } } })).ok()).toBeTruthy()
  const videoBytes = Buffer.alloc(64); videoBytes.write('ftyp', 4)
  expect((await request.post(`/api/events/${event.id}/media`, { multipart: { file: { name: 'Sin miniatura.mp4', mimeType: 'video/mp4', buffer: videoBytes } } })).ok()).toBeTruthy()
  expect((await request.post(`/api/events/${event.id}/playlists`, { data: { name: 'Por armar', isLoop: false, items: [] } })).ok()).toBeTruthy()
  const admin = await context.newPage()
  await admin.goto(`/admin?event=${event.id}`)
  const trigger = admin.getByRole('button', { name: 'Contenido para TV Patio' })
  await trigger.click()
  const dialog = admin.getByRole('dialog', { name: 'Elegir contenido' })
  const search = dialog.getByRole('searchbox', { name: 'Buscar contenido' })
  await expect(search).toBeFocused()
  for (const name of ['Playlists', 'Videos', 'Imágenes']) await expect(dialog.getByRole('heading', { name: new RegExp(name) })).toBeVisible()
  const playlist = dialog.getByRole('button', { name: 'Seleccionar playlist: Ambientación', exact: true })
  await expect(playlist.locator('img')).toHaveJSProperty('naturalWidth', 1)
  await expect(dialog.getByRole('button', { name: 'Seleccionar playlist: Por armar' })).toBeDisabled()
  await admin.screenshot({ path: testInfo.outputPath('picker-desktop.png') })
  await dialog.getByRole('button', { name: /^Videos/ }).click()
  await expect(dialog.locator('.content-picker-option')).toHaveCount(2)
  await expect(dialog.getByRole('button', { name: 'Seleccionar video: Apertura', exact: true }).locator('video')).toHaveClass(/is-ready/)
  await expect(dialog.getByText('Miniatura no disponible')).toBeVisible()
  await dialog.getByRole('button', { name: /^Todo/ }).click()
  await search.fill('  AMBIENTACION  ')
  await expect(dialog.locator('.content-picker-option')).toHaveCount(1)
  await expect(playlist).toBeVisible()
  await search.fill('inexistente')
  await expect(dialog.getByText('No encontramos ese contenido')).toBeVisible()
  await dialog.getByRole('button', { name: 'Limpiar búsqueda', exact: true }).first().click()
  await search.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()

  await admin.setViewportSize({ width: 360, height: 800 })
  await trigger.press('Enter')
  await expect(search).toBeFocused()
  const cancel = dialog.getByRole('button', { name: 'Cancelar', exact: true })
  await cancel.focus()
  await cancel.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Cerrar modal' })).toBeFocused()
  await dialog.getByRole('button', { name: 'Cerrar modal' }).press('Shift+Tab')
  await expect(cancel).toBeFocused()
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy()
  expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await dialog.evaluate(element => { element.scrollTop = 0 })
  await admin.screenshot({ path: testInfo.outputPath('picker-mobile.png') })
  await cancel.click()
  await admin.close()
})

test('selection waits for Play, supports retry, plays a playlist and retains transport controls', async ({ page: player, context, request }) => {
  const { event, display, image, playlist } = await setup(player, request)
  const admin = await context.newPage()
  await admin.goto(`/admin?event=${event.id}`)
  const controls = admin.getByRole('group', { name: 'Multimedia de TV Patio' })
  const trigger = controls.getByRole('button', { name: 'Contenido para TV Patio' })
  const dialog = admin.getByRole('dialog', { name: 'Elegir contenido' })
  const sent: string[] = []
  admin.on('request', request => { if (request.method() === 'POST' && /\/commands$|\/play$/.test(request.url())) sent.push(request.url()) })
  await trigger.click()
  await dialog.getByRole('button', { name: 'Seleccionar playlist: Ambientación', exact: true }).click()
  await expect(trigger).toContainText('Ambientación')
  await expect(controls.getByText('Listo para enviar')).toBeVisible()
  expect(sent).toHaveLength(0)
  await controls.getByRole('button', { name: 'Descartar selección' }).click()
  await expect(trigger).toContainText('Seleccionar contenido')
  await expect(controls.getByRole('button', { name: 'Reanudar', exact: true })).toBeDisabled()
  await trigger.click()
  await dialog.getByRole('button', { name: 'Seleccionar playlist: Ambientación', exact: true }).click()
  await admin.route(`**/api/playlists/${playlist.id}/play`, route => route.fulfill({ status: 503, json: { error: 'Servicio temporalmente no disponible' } }))
  await controls.getByRole('button', { name: 'Reproducir en TV Patio', exact: true }).click()
  await expect(controls.getByRole('alert')).toBeVisible()
  await expect(trigger).toContainText('Ambientación')
  await admin.unroute(`**/api/playlists/${playlist.id}/play`)
  const playResponse = admin.waitForResponse(response => response.url().endsWith(`/playlists/${playlist.id}/play`) && response.status() === 202)
  await controls.getByRole('button', { name: 'Reproducir en TV Patio', exact: true }).click()
  expect((await playResponse).request().postDataJSON()).toEqual({ targetType: 'display', targetId: display.id })
  await expect(controls.getByText('Acción confirmada por el reproductor')).toBeVisible({ timeout: 15000 })
  await expect(trigger).toContainText('Playlist · Cambiar')
  await expect(controls.getByRole('button', { name: 'Descartar selección' })).toHaveCount(0)
  await controls.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect(controls.getByRole('button', { name: 'Reanudar', exact: true })).toBeEnabled()
  await controls.getByRole('button', { name: 'Reanudar', exact: true }).click()
  await expect(controls.getByRole('button', { name: 'Pausar', exact: true })).toBeEnabled()

  await trigger.click()
  await dialog.getByRole('button', { name: 'Seleccionar imagen: Recepción', exact: true }).click()
  const mediaRequest = admin.waitForRequest(request => request.url().endsWith(`/displays/${display.id}/commands`) && request.postDataJSON().type === 'media.play')
  await controls.getByRole('button', { name: 'Reproducir en TV Patio', exact: true }).click()
  expect((await mediaRequest).postDataJSON().payload).toEqual({ mediaId: image.id })
  await expect(trigger).toContainText('Imagen · Cambiar')
  await expect(controls.getByText('Acción confirmada por el reproductor')).toBeVisible({ timeout: 15000 })
  await controls.getByRole('button', { name: /Repetir/ }).click()
  await expect(controls.getByRole('button', { name: /Repetir/ })).toHaveAttribute('aria-pressed', 'true')
  await controls.getByRole('button', { name: 'Detener contenido', exact: true }).click()
  await expect(controls.getByRole('button', { name: 'Detener contenido', exact: true })).toBeDisabled()
  await admin.close()
})
